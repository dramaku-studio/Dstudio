/** End-to-end LOCAL FIXTURE preview, generates playable MP4 using ffmpeg—not AI. */
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {join,resolve,relative} from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {createHttpVideoBridge} from '../../packages/providers/src/http-video-bridge.mjs';
import {startFixtureBridge} from '../../packages/providers/src/fixture-bridge.mjs';
import {createLocalVideoStore} from '../../packages/media/src/local-store.mjs';
const exec=promisify(execFile);
export async function runLocalVideoDemo(outDir=resolve(process.cwd(),'cp003-demo')){
  await mkdir(outDir,{recursive:true});
  const fixture=join(outDir,'fixture-generated-by-ffmpeg.mp4');
  await exec('ffmpeg',['-hide_banner','-loglevel','error','-y','-f','lavfi','-i','testsrc2=size=480x854:rate=24',
    '-t','2','-vf','drawbox=x=0:y=0:w=iw:h=150:color=black@0.7:t=fill','-c:v','mpeg4','-q:v','5','-pix_fmt','yuv420p',
    '-movflags','+faststart',fixture],{timeout:25000});
  const bridge=await startFixtureBridge({mp4Path:fixture});
  try{
    const api=createHttpVideoBridge({baseUrl:bridge.url,token:bridge.token,allowInsecureLoopback:true});
    const store=createLocalVideoStore({root:join(outDir,'private-assets')});
    const input={prompt:'Fixture video: abstract generated test pattern, no AI model used.'};
    const submit=await api.submit(input,{clientReference:'cp003_local_demo'});
    const status=await api.getStatus(submit.externalTaskId);
    if(status.state!=='succeeded')throw new Error('Fixture should succeed');
    const saved=await store.ingest(await api.openVideo(submit.externalTaskId));
    const manifest={checkpoint:'CP-003',mode:'LOCAL_FFMPEG_FIXTURE_NOT_AI',provider:'localhost-test-bridge',
      input,submit,status,asset:{sha256:saved.sha256,bytes:saved.bytes,width:saved.width,height:saved.height,
      durationSeconds:saved.durationSeconds,file:relative(outDir,saved.path)},
      note:'Playable test media; this does not verify a paid video model or PostgreSQL runtime.'};
    await writeFile(join(outDir,'manifest.json'),JSON.stringify(manifest,null,2));
    const html=`<!DOCTYPE html><html lang="id"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Dramasaku CP-003 | Fixture Video Demo</title><style>body{background:#09090b;color:#f4f4f5;font:16px system-ui;margin:0;padding:36px}main{max-width:960px;margin:auto}h1{font-size:30px}small{color:#a1a1aa}.pill{background:#7f1d1d;color:#fecaca;padding:6px 12px;border-radius:99px;display:inline-block}video{width:min(340px,100%);border-radius:18px;border:1px solid #3f3f46}pre{white-space:pre-wrap;background:#18181b;padding:20px;border-radius:14px;overflow-wrap:anywhere}a{color:#f87171}</style></head><body><main><span class="pill">LOCAL FIXTURE • NOT GENERATED BY AI</span><h1>Dramasaku Studio — CP-003</h1><p>Bridge HTTP → Job Submit → Status → MP4 Ingest → SHA-256 → Media QA</p><video controls preload="metadata" src="${manifest.asset.file}"></video><p><small>Video uji yang benar-benar dapat diputar, dibuat oleh ffmpeg di komputer lokal. Belum terhubung ke API model berbayar.</small></p><h2>Asset manifest</h2><pre>${JSON.stringify(manifest,null,2).replaceAll('<','&lt;')}</pre></main></body></html>`;
    await writeFile(join(outDir,'index.html'),html);
    return manifest;
  }finally{await bridge.close();}
}
if(process.argv[1]&&import.meta.url===new URL(`file://${process.argv[1]}`).href){
  const result=await runLocalVideoDemo(process.env.CP003_OUTPUT_DIR?resolve(process.env.CP003_OUTPUT_DIR):undefined);
  console.log(JSON.stringify({ok:true,mode:result.mode,asset:result.asset,manifest:'cp003-demo/manifest.json'},null,2));
}
